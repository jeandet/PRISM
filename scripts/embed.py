#!/usr/bin/env python3
"""embed.py <in> <out.cpp> <symbol>

Turns a binary file into a C++ source that defines, in namespace prism::raster::embedded, a function
`std::span<const std::uint8_t> <symbol>()` returning the file's bytes. Used by meson
(custom_target) to compile the TTF fonts into the firmware -- GCC 15 has #embed in C only, not
in C++, so the arrays are generated here instead.
"""

import sys


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write("usage: embed.py <in> <out.cpp> <symbol>\n")
        return 2
    src, out, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
    if not symbol.isidentifier():
        sys.stderr.write(f"embed.py: {symbol!r} is not a valid C++ identifier\n")
        return 2
    with open(src, "rb") as f:
        data = f.read()
    with open(out, "w") as f:
        f.write(f"// Generated by scripts/embed.py from {src} -- do not edit.\n")
        f.write("#include <cstddef>\n#include <cstdint>\n#include <span>\n\n")
        f.write("namespace prism::raster::embedded {\nnamespace {\n")
        f.write(f"const std::uint8_t {symbol}_data[] = {{\n")
        for i in range(0, len(data), 20):
            f.write("    " + ",".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",\n")
        f.write("};\n}\n\n")
        f.write(f"std::span<const std::uint8_t> {symbol}() {{\n")
        f.write(f"    return std::span<const std::uint8_t>({symbol}_data, sizeof {symbol}_data);\n")
        f.write("}\n\n")
        f.write("} // namespace prism::raster::embedded\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
